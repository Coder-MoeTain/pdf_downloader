def catalog_rows_from_ebooks() -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for item in EBOOK_SOURCES:
        rows.append({key: value for key, value in item.items() if key not in _PROVIDER_KEYS})
    return rows


