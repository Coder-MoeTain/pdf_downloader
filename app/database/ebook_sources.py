def _row(
    *,
    slug: str,
    display_name: str,
    description: str,
    family: str,
    category: str,
    backend: str,
    sort_order: int,
    subject: str = "",
    concept_id: str = "",
    query_extra: str = "",
    ia_clause: str = "",
    urls: dict[str, str] | None = None,
) -> dict[str, object]:
    links = urls or {}
    return {
        "slug": slug,
        "display_name": display_name,
        "description": description,
        "homepage_url": links["homepage_url"],
        "api_base_url": links["api_base_url"],
        "docs_url": links["docs_url"],
        "requires_key": False,
        "api_key_env": None,
        "sort_order": sort_order,
        "backend": backend,
        "family": family,
        "category": category,
        "subject": subject,
        "concept_id": concept_id,
        "query_extra": query_extra,
        "ia_clause": ia_clause,
        "content_kind": "ebook",
    }


